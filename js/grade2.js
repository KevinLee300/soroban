// 每小課先看例子，再用另一個情境試一次。答案以文字比對，方便選項換位。
function lesson(title, steps, question, choices, answer, hint, why, picture) {
  return { title, steps, question, choices, answer, hint, why, picture };
}

function multiplication(n) {
  const totals = [n, n * 2, n * 3];
  return lesson(n + " 的乘法", [
    "一排有 " + n + " 顆珠子。每多一排，就多 " + n + " 顆。",
    "指著圖一排一排數：" + totals.join("、") + "。每排一樣多，可以用乘法。",
    "每排 " + n + " 顆，有 3 排。" + n + " × 3 ＝ " + n * 3 + " 顆。"
  ], "再放一排，變成 4 排。共有幾顆？", [3, 4, 5].map(k => String(n * k)), String(n * 4),
  "從 " + n * 3 + " 再加一排的 " + n + " 顆。", n + " × 4 ＝ " + n * 4 + "。", { rows: 3, count: n });
}

